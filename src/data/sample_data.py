def generate_rows() -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    for company in DEMO_COMPANIES:
        annual = _bank_annual(company) if company.kind == "bank" else _industrial_annual(company)
        for year, values in annual.items():
            period_end = _year_end(year)
            published = _publication(period_end, 90)
            for item, value in values.items():
                statement = STATEMENT_OF.get(item)
                if statement is None:
                    continue
                if item == "shares_outstanding":
                    rows.append(_row(company, period_end, "annual", "balance", item, value, published, unit="million"))
                    continue
                rows.append(_row(company, period_end, "annual", statement, item, value, published))

        # Four cumulative quarters for the latest year, so TTM logic is exercised.
        latest = annual[max(YEARS)]
        prior_year = annual[max(YEARS) - 1]
        cumulative = {item: 0.0 for item in FLOW_ITEMS}
        for quarter, weight in enumerate(QUARTER_WEIGHTS, start=1):
            period_end = _dt.date(max(YEARS), quarter * 3, [31, 30, 30, 31][quarter - 1])
            published = _publication(period_end, 45)
            for item in FLOW_ITEMS:
                if item not in latest or item not in prior_year:
                    continue
                delta = latest[item] - prior_year[item]
                incremental = latest[item] * weight
                cumulative[item] += incremental
                statement = STATEMENT_OF[item]
                rows.append(_row(company, period_end, "quarter", statement, item, cumulative[item], published))
            for item, value in latest.items():
                statement = STATEMENT_OF.get(item)
                if statement is None or item in FLOW_ITEMS:
                    continue
                rows.append(_row(company, period_end, "quarter", statement, item, value, published))
            if company.kind == "bank":
                rows.append(
                    _row(company, period_end, "quarter", "balance", "npl_ratio", company.npl_ratio * 100, published, unit="percent")
                )
                rows.append(
                    _row(company, period_end, "quarter", "balance", "car_ratio", company.car_ratio * 100, published, unit="percent")
                )
        if company.kind == "bank":
            for year, values in annual.items():
                period_end = _year_end(year)
                published = _publication(period_end, 90)
                rows.append(_row(company, period_end, "annual", "balance", "npl_ratio", company.npl_ratio * 100, published, unit="percent"))
                rows.append(_row(company, period_end, "annual", "balance", "car_ratio", company.car_ratio * 100, published, unit="percent"))
    return rows


TARGET_PE = {"DEMO-MFG": 12.0, "DEMO-CNS": 16.0, "DEMO-MIN": 7.0, "DEMO-BNK": 10.0}


def generate_prices(seed: int = 11) -> pd.DataFrame:
    """Random-walk prices anchored to a plausible starting multiple of earnings."""
    rng = random.Random(seed)
    end = _dt.date.today() - _dt.timedelta(days=1)
    start = _dt.date(max(YEARS) - 2, 1, 2)
    days = pd.bdate_range(start, end)
    records = []
    for index, company in enumerate(DEMO_COMPANIES):
        annual = _bank_annual(company) if company.kind == "bank" else _industrial_annual(company)
        latest_net = annual[max(YEARS)]["net_income"] * 1e6  # million IDR -> IDR
        anchor = TARGET_PE.get(company.ticker, 12.0) * latest_net / company.shares
        price = max(100.0, anchor * 0.85)
        drift = 0.00018 + 0.00004 * index
        volatility = 0.012 + 0.0015 * index
        for date in days:
            shock = rng.gauss(drift, volatility)
            price = max(50.0, price * (1 + shock))
            volume = rng.randint(2_000_000, 40_000_000)
            records.append(
                {
                    "ticker": company.ticker,
                    "date": date.date().isoformat(),
                    "close": round(price, 2),
                    "volume": volume,
                    "value": round(price * volume, 2),
                }
            )
    return pd.DataFrame(records)


def generate_benchmark(seed: int = 23) -> pd.DataFrame:
    rng = random.Random(seed)
    days = pd.bdate_range(_dt.date(max(YEARS) - 2, 1, 2), _dt.date.today() - _dt.timedelta(days=1))
    level = 6600.0
    records = []
    for date in days:
        level = max(1000.0, level * (1 + rng.gauss(0.00025, 0.009)))
        records.append({"date": date.date().isoformat(), "close": round(level, 2), "label": "IHSG (synthetic)"})
    return pd.DataFrame(records)


def write_sample_files(directory: Optional[Path] = None) -> Dict[str, Path]:
    directory = Path(directory) if directory else SAMPLE_DIR
    directory.mkdir(parents=True, exist_ok=True)
    financials = pd.DataFrame(generate_rows())
    prices = generate_prices()
    benchmark = generate_benchmark()

    financials_path = directory / "demo_financials.csv"
    prices_path = directory / "demo_prices.csv"
    benchmark_path = directory / "demo_benchmark.csv"
    readme_path = directory / "README.md"

    financials.to_csv(financials_path, index=False, encoding="utf-8-sig")
    prices.to_csv(prices_path, index=False, encoding="utf-8-sig")
    benchmark.to_csv(benchmark_path, index=False, encoding="utf-8-sig")
    readme_path.write_text(
        "# Synthetic demonstration data\n\n"
        "Everything in this folder is generated arithmetically by "
        "`src/data/sample_data.py`. The issuers do **not** exist and the prices are "
        "random walks. It exists so the application can be exercised end to end.\n\n"
        "Load it from the Data Management page, or run:\n\n"
        "```\npython scripts/seed_demo_data.py\n```\n\n"
        "Real data must be imported from IDX filings (https://www.idx.co.id/) using "
        "`financial_template.csv`, with the source URL recorded on every row.\n",
        encoding="utf-8",
    )
    return {
        "financials": financials_path,
        "prices": prices_path,
        "benchmark": benchmark_path,
        "readme": readme_path,
    }


def seed_database(repos, directory: Optional[Path] = None) -> Dict[str, Any]:
    """Import the synthetic files into the database."""
    from src.data.csv_importer import import_financials, import_prices
    from src.data.financial_parser import build_periods

    paths = write_sample_files(directory)
    result = import_financials(paths["financials"])
    saved = repos.financials.save_periods(build_periods(result.rows))

    for company in DEMO_COMPANIES:
        repos.companies.upsert(
            ticker=company.ticker,
            name=company.name,
            sector=company.sector,
            shares_outstanding=company.shares,
            source_url="https://www.idx.co.id/",
            is_synthetic=True,
            notes=SOURCE_NOTE,
        )

    price_frame = pd.read_csv(paths["prices"])
    price_rows = repos.prices.upsert_many(price_frame)

    benchmark = pd.read_csv(paths["benchmark"])
    for record in benchmark.to_dict("records"):
        repos.benchmarks.upsert(
            str(record.get("label", "IHSG (synthetic)")),
            pd.Timestamp(record["date"]).date(),
            float(record["close"]),
        )

    return {
        "periods_saved": saved,
        "rows_imported": len(result.rows),
        "price_rows": price_rows,
        "companies": [company.ticker for company in DEMO_COMPANIES],
        "validation": result.report.summary(),
    }
