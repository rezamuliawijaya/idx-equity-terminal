def fiscal_years(today: Optional[_dt.date] = None) -> List[int]:
    """Five completed fiscal years ending with the most recent audited year."""
    today = today or _dt.date.today()
    latest = today.year - 1 if today.month >= 5 else today.year - 2
    return list(range(latest - 4, latest + 1))


def _year_end(year: int) -> _dt.date:
    return _dt.date(year, 12, 31)


