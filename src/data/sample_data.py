def _publication(period_end: _dt.date, lag_days: int) -> _dt.date:
    return period_end + _dt.timedelta(days=lag_days)


def _row(
    company: DemoCompany,
    period_end: _dt.date,
    period_type: str,
    statement: str,
    item: str,
    value: float,
    publication_date: _dt.date,
    unit: str = "million",
    period_basis: str = "cumulative",
) -> Dict[str, Any]:
    return {
        "ticker": company.ticker,
        "company_name": company.name,
        "sector": company.sector,
        "period_end": period_end.isoformat(),
        "period_type": period_type,
        "period_basis": period_basis if period_type == "quarter" else "cumulative",
        "statement": statement,
        "line_item": item,
        "value": round(float(value), 2),
        "unit": unit,
        "currency": "IDR",
        "is_consolidated": True,
        "source_url": "https://www.idx.co.id/",
        "publication_date": publication_date.isoformat(),
        "notes": SOURCE_NOTE,
    }


def _industrial_annual(company: DemoCompany) -> Dict[int, Dict[str, float]]:
    output: Dict[int, Dict[str, float]] = {}
    equity_prior: Optional[float] = None
    for index, year in enumerate(YEARS):
        revenue = company.revenue_2020 * (1 + company.growth) ** index
        cogs = revenue * (1 - company.gross_margin)
        gross = revenue - cogs
        opex = revenue * company.opex_pct
        operating = gross - opex
        da = revenue * company.da_pct
        ebitda = operating + da
        assets = revenue * company.asset_intensity
        equity_target = assets * company.equity_ratio

        if equity_prior is None:
            equity = equity_target
        else:
            # Keep the equity ratio approximately stable while remaining arithmetically consistent.
            equity = equity_target * 0.55 + (equity_prior * 0.45)

        liabilities = assets - equity
        debt = liabilities * 0.32
        interest = debt * 0.095
        pretax = operating - interest
        tax = max(0.0, pretax * company.tax_rate)
        net = pretax - tax
        dividends = max(0.0, net * company.payout)
        equity_prior = equity

        current_assets = assets * 0.45
        inventory = assets * company.inventory_pct
        receivables = revenue * company.receivables_pct
        cash = assets * company.cash_pct
        other_current = max(0.0, current_assets - inventory - receivables - cash)

        cfo = net + da * 0.85
        capex = revenue * company.capex_pct

        output[year] = {
            "revenue": revenue,
            "cost_of_revenue": cogs,
            "gross_profit": gross,
            "operating_expenses": opex,
            "operating_income": operating,
            "depreciation_amortization": da,
            "ebitda": ebitda,
            "interest_expense": interest,
            "pretax_income": pretax,
            "income_tax": tax,
            "net_income": net,
            "net_income_parent": net,
            "eps": net * 1e6 / company.shares,
            "cash": cash,
            "receivables": receivables,
            "inventory": inventory,
            "other_current_assets": other_current,
            "current_assets": current_assets,
            "ppe": assets * 0.42,
            "total_assets": assets,
            "current_liabilities": liabilities * 0.55,
            "short_term_debt": debt * 0.45,
            "long_term_debt": debt * 0.55,
            "total_debt": debt,
            "total_liabilities": liabilities,
            "equity": equity,
            "equity_parent": equity,
            "shares_outstanding": company.shares / 1e6,
            "cfo": cfo,
            "capex": capex,
            "cfi": -capex * 1.1,
            "cff": dividends - debt * 0.02,
            "fcf": cfo - capex,
            "dividends_paid": -dividends,
        }
    return output


def _bank_annual(company: DemoCompany) -> Dict[int, Dict[str, float]]:
    output: Dict[int, Dict[str, float]] = {}
    equity_prior: Optional[float] = None
    for index, year in enumerate(YEARS):
        revenue = company.revenue_2020 * (1 + company.growth) ** index
        nii = revenue * 0.78
        other_income = revenue * 0.22
        assets = revenue * company.asset_intensity
        loans = assets * company.loan_to_assets
        deposits = assets * 0.72
        npl = loans * company.npl_ratio

        opex = revenue * company.cost_income
        provisions = loans * 0.006
        operating = revenue - opex - provisions
        da = revenue * company.da_pct
        ebitda = operating + da

        equity_target = assets * company.equity_ratio
        equity = equity_target if equity_prior is None else equity_target * 0.6 + equity_prior * 0.4
        liabilities = assets - equity
        interest = deposits * 0.032  # cost of funds, for coverage context only

        pretax = operating
        tax = max(0.0, pretax * company.tax_rate)
        net = pretax - tax
        dividends = max(0.0, net * company.payout)
        equity_prior = equity

        cfo = net + provisions
        capex = revenue * company.capex_pct

        output[year] = {
            "revenue": revenue,
            "operating_expenses": opex,
            "operating_income": operating,
            "depreciation_amortization": da,
            "ebitda": ebitda,
            "interest_expense": interest,
            "pretax_income": pretax,
            "income_tax": tax,
            "net_income": net,
            "net_income_parent": net,
            "eps": net * 1e6 / company.shares,
            "net_interest_income": nii,
            "other_operating_income": other_income,
            "provision_expense": provisions,
            "cash": assets * 0.09,
            "current_assets": assets * 0.22,
            "loans": loans,
            "total_assets": assets,
            "current_liabilities": deposits * 0.85,
            "customer_deposits": deposits,
            "total_liabilities": liabilities,
            "equity": equity,
            "equity_parent": equity,
            "shares_outstanding": company.shares / 1e6,
            "npl": npl,
            "cfo": cfo,
            "capex": capex,
            "cfi": -capex * 1.2,
            "cff": dividends - deposits * 0.01,
            "fcf": cfo - capex,
            "dividends_paid": -dividends,
        }
    return output


